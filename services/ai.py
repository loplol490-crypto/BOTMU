import random


async def get_ai_response(message: str, user_id: int):
    text = message.lower().strip()

    # --- привет ---
    if any(x in text for x in ["привет", "салам", "hello", "hi"]):
        return random.choice([
            "👋 Салам! Рад тебя видеть в Кыргызстане 🇰🇬",
            "👋 Привет! Куда отправимся сегодня?",
            "🤖 Здарова! Я твой гид по Кыргызстану 😄"
        ])

    # --- Бишкек ---
    if "бишкек" in text:
        return random.choice([
            "🏙 Бишкек — столица Кыргызстана. Советую: Ошский базар, площадь Ала-Тоо, Дубовый парк.",
            "🏙 В Бишкеке классно гулять вечером в центре города.",
            "🏙 Хочешь — сделаю тебе маршрут на 1 день по Бишкеку."
        ])

    # --- Иссык-Куль ---
    if "иссык" in text:
        return random.choice([
            "🌊 Иссык-Куль — одно из самых красивых мест в регионе.",
            "🌊 Там горы и озеро рядом — очень красивый вид.",
            "🌊 Могу подсказать, куда лучше поехать на отдых."
        ])

    # --- еда ---
    if any(x in text for x in ["еда", "поесть", "кухня"]):
        return random.choice([
            "🍜 Попробуй бешбармак, лагман и манты — это база Кыргызстана.",
            "🍜 Кыргызская кухня очень сытная и вкусная 😄",
            "🍜 В Бишкеке есть много недорогих кафе с национальной едой."
        ])

    # --- транспорт ---
    if any(x in text for x in ["такси", "автобус", "маршрутка"]):
        return random.choice([
            "🚌 В Бишкеке удобно ездить на маршрутках и такси через приложения.",
            "🚕 Такси дешёвое, особенно по городу.",
            "🚌 Маршрутки ходят почти везде."
        ])

    # --- fallback ---
    return random.choice([
        "🤖 Я пока учусь 😄 Спроси про Бишкек, еду или Иссык-Куль",
        "💬 Попробуй спросить: куда сходить в Бишкеке",
        "🌍 Я твой гид-друг по Кыргызстану 🇰🇬"
    ])
