import random

async def get_ai_response(message: str) -> str:
    text = message.lower()

    # простой "умный" гид по Кыргызстану
    if "привет" in text:
        return "👋 Привет! Я твой AI-гид по Кыргызстану. Чем помочь?"

    if "бишкек" in text:
        return "🏙 Бишкек — столица Кыргызстана. Могу подсказать места, кафе или маршруты."

    if "отель" in text or "где остановиться" in text:
        return "🏨 Могу помочь найти отели в Бишкеке, Оше и на Иссык-Куле."

    if "иссык-куль" in text:
        return "🌊 Иссык-Куль — одно из самых красивых мест. Летом там топ отдых!"

    if "еда" in text:
        return "🍜 В Кыргызстане попробуй: бешбармак, лагман, манты."

    # случайные дружеские ответы
    replies = [
        "🤖 Я пока учусь, но уже могу помогать тебе по Кыргызстану!",
        "🌍 Спроси меня про города, еду или места отдыха.",
        "💬 Я твой гид-друг. Что хочешь узнать?"
    ]

    return random.choice(replies)
