import random


async def get_ai_response(message: str, user_id: int):
    text = message.lower().strip()

    # --- привет ---
    if any(x in text for x in ["привет", "салам", "hello", "hi"]):
        return random.choice([
            "👋 Привет! Я твой AI-друг и гид по Кыргызстану 🇰🇬",
            "👋 Салам! Рад тебя видеть 😊",
            "🤖 Привет! Куда отправимся сегодня?"
        ])

    # --- настроение / разговор ---
    if any(x in text for x in ["как дела", "как ты"]):
        return random.choice([
            "😊 У меня всё отлично! Готов помочь тебе по Кыргызстану",
            "🤖 Работаю и учусь быть лучшим гидом для тебя",
            "🔥 Всё супер! Куда поедем?"
        ])

    # --- Бишкек ---
    if "бишкек" in text:
        return random.choice([
            "🏙 Бишкек — столица Кыргызстана. Хочешь места или кафе?",
            "🏙 Там стоит посмотреть Ошский базар и площадь Ала-Тоо",
            "🏙 Могу составить тебе маршрут по Бишкеку"
        ])

    # --- Иссык-Куль ---
    if "иссык" in text:
        return random.choice([
            "🌊 Иссык-Куль — топ место для отдыха в Кыргызстане",
            "🌊 Там горы, пляжи и очень красивый вид",
            "🌊 Хочешь — подберу тебе маршрут туда"
        ])

    # --- еда ---
    if any(x in text for x in ["еда", "поесть", "кухня"]):
        return random.choice([
            "🍜 Попробуй бешбармак, лагман и манты",
            "🍜 Кыргызская кухня очень вкусная и сытная",
            "🍜 Могу подсказать лучшие кафе в Бишкеке"
        ])

    # --- если не понял ---
    return random.choice([
        "🤖 Я пока учусь 😄 Спроси про Бишкек, еду или Иссык-Куль",
        "💬 Я твой гид-друг по Кыргызстану 🇰🇬",
        "🌍 Напиши проще — я помогу тебе"
    ])
